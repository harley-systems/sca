#!/bin/bash
# Generate the command reference from the help files
#
# Usage: build-docs.sh
#
# Writes docs/commands/<command>.md for every src/<command>/help/ directory, and
# the index docs/commands.md. Run 'make docs' rather than calling it directly.
#
# Each command page has a section for the command and one for each subcommand
# (src/<command>/<subcommand>/help/), made of:
#   command_title.txt, abstract.txt - shown as in 'sca <command> --help'
#   syntax.txt          - with the option placeholders substituted by
#                         build-help.sh, so it matches the --help output
#   further_read.txt    - shown under "See also"
#   reference.md        - optional, hand-written markdown (examples, notes)
#                         appended to the section as is
#
# The index is rendered from src/help/reference.md, where
#   @@@SCA OPTIONS@@@   - becomes the global options (src/help/options.txt)
#   @@@COMMAND INDEX@@@ - becomes a table linking every command page
#
# @@@UBUNTU VERSION ID@@@ is replaced by $UBUNTU_VERSION_ID, which the Makefile
# passes in, as it is in build/sca.sh.
#
# The output is deterministic: changing one command's help files changes only
# that command's page. Unchanged pages are not rewritten, and pages of commands
# that no longer exist are removed.

set -e

cd "$(dirname "$0")/.."
export LC_ALL=C
: "${UBUNTU_VERSION_ID:?is not set: run 'make docs'}"

DOCS_DIR=docs
PAGES_DIR="${DOCS_DIR}/commands"

tmp=$(mktemp -d)
trap 'rm -rf "${tmp}"' EXIT
printf '@@@SYNTAX@@@\n' > "${tmp}/syntax.tpl"

# print a file, making sure the output ends with a newline
print_file() {
    cat "$1"
    if [ -n "$(tail -c 1 "$1")" ]; then
        echo
    fi
}

# print a fenced text block holding the given files, separated by a blank line
text_block() {
    local file first=1
    echo '```text'
    for file in "$@"; do
        [ -s "${file}" ] || continue
        [ -n "${first}" ] || echo
        first=
        print_file "${file}"
    done
    echo '```'
}

# print the one-line description of <name> from the "allowed values" list of a
# syntax file ("  - <name>   - <description>", the leading "- " is optional);
# indented lines that follow are continuations. For example, with name=crt_pub_ssh
#   "  - crt_pub_ssh   - batch creation of certificate, public key and public"
#   "                    key in ssh format"
# prints "batch creation of certificate, public key and public key in ssh format"
describe() {
    local syntax_file=$1 name=$2
    awk -v name="${name}" '
        found && /^ +[^ -]/ && !/^ *[^ ]+  *- / { sub(/^ +/, ""); desc = desc " " $0; next }
        found { exit }
        $0 ~ "^ *(- )?" name "  *- " { sub("^ *(- )?" name "  *- ", ""); desc = $0; found = 1 }
        END { gsub(/\|/, "\\|", desc); print desc }
    ' "${syntax_file}"
}

# print the body of a command's or subcommand's section
# $1 = help directory, $2 = parent command (empty for a command)
render_section() {
    local help_dir=$1 parent=$2

    text_block "${help_dir}/command_title.txt" "${help_dir}/abstract.txt"

    # the global options are listed once, in the index, rather than in every
    # section
    rm -rf "${tmp}/help"
    mkdir "${tmp}/help"
    if [ -f "${help_dir}/options.txt" ]; then
        cp "${help_dir}/options.txt" "${tmp}/help/"
    fi
    sed '/^@@@SCA OPTIONS@@@$/d' "${help_dir}/syntax.txt" > "${tmp}/help/syntax.txt"
    HELP_TEMPLATE="${tmp}/syntax.tpl" ./scripts/build-help.sh \
        "${tmp}/syntax.raw" "${tmp}/help" "${parent}"
    cat -s "${tmp}/syntax.raw" > "${tmp}/syntax.txt"
    echo
    echo '**Syntax**'
    echo
    text_block "${tmp}/syntax.txt"

    if [ -s "${help_dir}/further_read.txt" ]; then
        echo
        echo '**See also**'
        echo
        text_block "${help_dir}/further_read.txt"
    fi

    if [ -f "${help_dir}/reference.md" ]; then
        echo
        print_file "${help_dir}/reference.md"
    fi
}

# print the page of a command
render_page() {
    local command=$1 sub description subcommands=()

    for sub in src/"${command}"/*/help/command_title.txt; do
        [ -f "${sub}" ] || continue
        sub=${sub#src/"${command}"/}
        subcommands+=("${sub%%/*}")
    done

    echo "<!-- Generated by scripts/build-docs.sh from src/${command}/**/help/. Do not edit: change the help files and run 'make docs'. -->"
    echo
    echo "# sca ${command}"
    echo
    echo '[← Command reference](../commands.md)'
    echo
    echo "\`<sca_options>\` are the [global options](../commands.md#global-options)."
    echo
    render_section "src/${command}/help" ""

    if [ ${#subcommands[@]} -gt 0 ]; then
        echo
        echo '**Subcommands**'
        echo
        for sub in "${subcommands[@]}"; do
            description=$(describe "src/${command}/help/syntax.txt" "${sub}")
            echo "- [${sub}](#sca-${command}-${sub})${description:+ - ${description}}"
        done
        for sub in "${subcommands[@]}"; do
            echo
            echo '---'
            echo
            echo "## sca ${command} ${sub}"
            echo
            render_section "src/${command}/${sub}/help" "${command}"
        done
    fi
}

# print the table of commands for the index
render_command_index() {
    local command
    echo '| Command | Description |'
    echo '|---------|-------------|'
    for command in "${commands[@]}"; do
        echo "| [${command}](commands/${command}.md) |" \
            "$(describe src/help/syntax.txt "${command}") |"
    done
}

# commands are the src/ directories with help files; src/common/help only
# holds the help template
commands=()
for title in src/*/help/command_title.txt; do
    command=${title#src/}
    commands+=("${command%%/*}")
done

mkdir -p "${tmp}/out/commands"
for command in "${commands[@]}"; do
    render_page "${command}" > "${tmp}/page.md"
    sed -e "s/@@@UBUNTU VERSION ID@@@/${UBUNTU_VERSION_ID}/g" "${tmp}/page.md" \
        > "${tmp}/out/commands/${command}.md"
done

text_block src/help/options.txt > "${tmp}/sca_options.md"
render_command_index > "${tmp}/command_index.md"
sed -e "/^@@@SCA OPTIONS@@@\$/{r ${tmp}/sca_options.md" -e 'd}' \
    -e "/^@@@COMMAND INDEX@@@\$/{r ${tmp}/command_index.md" -e 'd}' \
    src/help/reference.md > "${tmp}/out/commands.md"

# install the pages, touching only those whose content changed
mkdir -p "${PAGES_DIR}"
for page in "${PAGES_DIR}"/*.md; do
    [ -f "${page}" ] || continue
    if [ ! -f "${tmp}/out/commands/${page##*/}" ]; then
        rm "${page}"
        echo "removed ${page}"
    fi
done
for page in "${tmp}"/out/commands.md "${tmp}"/out/commands/*.md; do
    target=${DOCS_DIR}/${page#"${tmp}"/out/}
    if ! cmp -s "${page}" "${target}"; then
        cp "${page}" "${target}"
        echo "updated ${target}"
    fi
done
